// 将数据转换为 YAML 格式写入 data/airports.yaml
function toYAML(obj, indent = 0) {
  const pad = ' '.repeat(indent);
  if (Array.isArray(obj)) {
    return obj.map(item => {
      if (typeof item === 'object' && item !== null) {
        const keys = Object.keys(item);
        const firstKey = keys[0];
        let res = `${pad}- ${firstKey}: ${formatYAMLVal(item[firstKey])}\n`;
        for (let i = 1; i < keys.length; i++) {
          const k = keys[i];
          res += `${pad}  ${k}: ${formatYAMLVal(item[k], indent + 2)}\n`;
        }
        return res;
      }
      return `${pad}- ${formatYAMLVal(item)}\n`;
    }).join('');
  }
  let res = '';
  for (const k of Object.keys(obj)) {
    res += `${pad}${k}: ${formatYAMLVal(obj[k], indent)}\n`;
  }
  return res;
}

function formatYAMLVal(val, indent = 0) {
  if (typeof val === 'string') {
    if (val.includes('\n')) {
      return `|\n${val.split('\n').map(l => ' '.repeat(indent + 2) + l).join('\n')}`;
    }
    if (val.includes(': ') || val.includes('#') || val.includes('"') || val.includes("'") || val.includes('[') || val.includes('{')) {
      return JSON.stringify(val);
    }
    return JSON.stringify(val);
  }
  if (typeof val === 'boolean' || typeof val === 'number') {
    return String(val);
  }
  if (val === null || val === undefined) {
    return '""';
  }
  return JSON.stringify(val);
}

